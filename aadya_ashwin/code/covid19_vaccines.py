import networkx as nx

def build_graph(link_map):
    """
    Build a directed graph from the link map.
    Edge A → B means: Article A contains a hyperlink to Article B
    """
    G = nx.DiGraph()  # Directed graph

    for article in filtered :
        G.add_node(article)

    for article, linked_articles in link_map.items() :
        for target in linked_articles:
            G.add_edge(article, target)

    return G

with open("/content/drive/MyDrive/DSP_Project_Data/links.json", "r") as f:
    link_map = json.load(f)

G = build_graph(link_map)

print(f"Nodes (articles): {G.number_of_nodes()}")
print(f"Edges (links): {G.number_of_edges()}")

def compute_metrics(G):
    """Compute key graph metrics for every node."""

    in_degree = dict(G.in_degree())

    out_degree = dict(G.out_degree())

    pagerank = nx.pagerank(G, alpha=0.85)

    # Betweenness centrality = how often this article is a "bridge"
    # NOTE: This is slow for large graphs, sample if needed
    if G.number_of_nodes() < 500:
        betweenness = nx.betweenness_centrality(G)
    else:
        betweenness = nx.betweenness_centrality(G, k=100)  # approximate

    # Build results dataframe
    df = pd.DataFrame({
        "article": list(G.nodes()),
        "in_degree": [in_degree[n] for n in G.nodes()],
        "out_degree": [out_degree[n] for n in G.nodes()],
        "pagerank": [pagerank[n] for n in G.nodes()],
        "betweenness": [betweenness[n] for n in G.nodes()]
    })

    df = df.sort_values("pagerank", ascending=False)
    return df

metrics_df = compute_metrics(G)
print("\nTop 10 Most Important Articles (by PageRank):")
