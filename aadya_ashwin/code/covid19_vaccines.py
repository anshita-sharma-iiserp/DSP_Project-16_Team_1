# HELPER 1: Get articles directly inside a category
# ─────────────────────────────────────────────
def get_category_members(category, limit=500):
    """Fetch all article titles from a Wikipedia category (pages only)."""
    articles = []
    cmcontinue = None

    while True:
        params = {
            'action':  'query',
            'list':    'categorymembers',
            'cmtitle': f'Category:{category}',
            'cmlimit': 'max',
            'cmtype':  'page',       # articles only, not subcategories
            'format':  'json'
        }
        if cmcontinue:
            params['cmcontinue'] = cmcontinue

        r = SESSION.get(url, params=params, timeout=10).json()
        for member in r.get('query', {}).get('categorymembers', []):
            articles.append(member['title'])

        if 'continue' in r and len(articles) < limit:
            cmcontinue = r['continue']['cmcontinue']
        else:
            break
        time.sleep(0.3)

    return articles


# ─────────────────────────────────────────────
# HELPER 2: Get subcategories inside a category
# ─────────────────────────────────────────────
def get_subcategories(category):
    """Fetch all subcategory names inside a Wikipedia category."""
    url = 'https://en.wikipedia.org/w/api.php'
    params = {
        'action':  'query',
        'list':    'categorymembers',
        'cmtitle': f'Category:{category}',
        'cmtype':  'subcat',         # subcategories only
        'cmlimit': 100,
        'format':  'json'
    }
    r = SESSION.get(url, params=params, timeout=10).json()
    # Strip the "Category:" prefix for reuse in get_category_members()
    return [
        m['title'].replace('Category:', '')
        for m in r.get('query', {}).get('categorymembers', [])
    ]


